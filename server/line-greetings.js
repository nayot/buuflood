/**
 * Which greeting fits a referral's stored screening (`mentalOf()` in line.js), or none yet.
 * @param {{level?:string, q9?:number|null, q8?:number|null, flags?:string[], crisis?:boolean}|null} m
 */
export function greetingCase(m) {
  if (!m?.level) return 'unknown';
  if (m.level === 'yellow') return (m.q8 ?? 0) >= 1 ? 'yellow8q' : 'yellow';
  if (m.level === 'red') {
    const onlyDepression = !m.crisis && (m.flags || []).every((f) => f === '9Q ≥ 19');
    return onlyDepression && (m.flags || []).length ? 'red' : 'redRisk';
  }
  return 'unknown'; // green: the villager asked for advice themselves
}

export const greeting = (m, test = false) => `${test ? '[ทดสอบ] ' : ''}${GREETINGS[greetingCase(m)]}`;
